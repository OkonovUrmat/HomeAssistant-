import SwiftUI
import Observation
import Core
import DesignSystem

@MainActor
@Observable
public final class InstructionDetailViewModel {
    public struct Content {
        public var instruction: Instruction
        public var breadcrumb: String
        public var hazard: HazardLevel
    }

    public enum State {
        case loading
        case loaded(Content)
        case notFound
        case failed(String)
    }

    public private(set) var state: State = .loading

    private let instructionID: Instruction.ID
    private let instructionRepository: any InstructionRepository
    private let categoryRepository: any CategoryRepository

    public init(
        instructionID: Instruction.ID,
        instructionRepository: any InstructionRepository,
        categoryRepository: any CategoryRepository
    ) {
        self.instructionID = instructionID
        self.instructionRepository = instructionRepository
        self.categoryRepository = categoryRepository
    }

    public var title: String {
        if case .loaded(let content) = state { return content.instruction.title }
        return ""
    }

    public func load() async {
        do {
            guard let instruction = try await instructionRepository.fetchInstruction(id: instructionID) else {
                state = .notFound
                return
            }
            let tree = CategoryTree(try await categoryRepository.fetchCategories())
            state = .loaded(Content(
                instruction: instruction,
                breadcrumb: instruction.categoryID.map { tree.breadcrumb(for: $0) } ?? "",
                hazard: instruction.categoryID.map { tree.effectiveHazard(of: $0) } ?? .normal
            ))
        } catch is CancellationError {
        } catch {
            state = .failed(error.localizedDescription)
        }
    }
}

/// Read-only procedure. The step-by-step run mode with checklists comes in Phase 3.
public struct InstructionDetailView: View {
    @State private var viewModel: InstructionDetailViewModel

    public init(viewModel: InstructionDetailViewModel) {
        _viewModel = State(initialValue: viewModel)
    }

    public var body: some View {
        Group {
            switch viewModel.state {
            case .loading:
                ProgressView()
            case .notFound:
                ContentUnavailableView("Not Found", systemImage: "questionmark.folder", description: Text("This procedure may have been deleted."))
            case .failed(let message):
                ContentUnavailableView("Couldn't Load", systemImage: "exclamationmark.triangle", description: Text(message))
            case .loaded(let content):
                list(content)
            }
        }
        .navigationTitle(viewModel.title)
        .navigationBarTitleDisplayMode(.inline)
        .task { await viewModel.load() }
    }

    private func list(_ content: InstructionDetailViewModel.Content) -> some View {
        let instruction = content.instruction
        return List {
            Section {
                VStack(alignment: .leading, spacing: DS.Spacing.s) {
                    Text(instruction.title)
                        .font(.title2.weight(.bold))
                    if !content.breadcrumb.isEmpty {
                        Text(content.breadcrumb)
                            .font(.subheadline)
                            .foregroundStyle(.secondary)
                    }
                    ProvenanceBadge(instruction.provenance)
                    if instruction.provenance == .aiSuggestion {
                        Text("Generated by the assistant and not verified. Check it against your documentation before following it.")
                            .font(.footnote)
                            .foregroundStyle(.orange)
                    }
                    if content.hazard != .normal {
                        HazardBanner(content.hazard)
                    }
                    if !instruction.summary.isEmpty {
                        Text(instruction.summary)
                            .foregroundStyle(.secondary)
                    }
                }
                .listRowBackground(Color.clear)
                .listRowInsets(EdgeInsets())
            }

            if !instruction.warnings.isEmpty {
                Section("Warnings") {
                    ForEach(instruction.warnings, id: \.self) { warning in
                        Label(warning, systemImage: "exclamationmark.triangle.fill")
                            .foregroundStyle(.red)
                    }
                }
            }

            if !instruction.requiredEquipment.isEmpty {
                Section("You'll Need") {
                    ForEach(instruction.requiredEquipment, id: \.self) { Label($0, systemImage: "wrench.adjustable") }
                }
            }

            if !instruction.preconditions.isEmpty {
                Section("Before You Start") {
                    ForEach(instruction.preconditions, id: \.self) { Label($0, systemImage: "checkmark.circle") }
                }
            }

            Section("Steps") {
                ForEach(Array(instruction.steps.enumerated()), id: \.element.id) { index, step in
                    StepRow(number: index + 1, step: step)
                }
            }

            if !instruction.expectedResult.isEmpty {
                Section("Expected Result") {
                    Label(instruction.expectedResult, systemImage: "flag.checkered")
                }
            }

            if !instruction.troubleshooting.isEmpty {
                Section("Troubleshooting") {
                    ForEach(instruction.troubleshooting) { tip in
                        VStack(alignment: .leading, spacing: DS.Spacing.xxs) {
                            Text(tip.problem).font(.subheadline.weight(.semibold))
                            Text(tip.solution).font(.subheadline).foregroundStyle(.secondary)
                        }
                    }
                }
            }
        }
        .listStyle(.insetGrouped)
    }
}

private struct StepRow: View {
    let number: Int
    let step: InstructionStep

    var body: some View {
        HStack(alignment: .firstTextBaseline, spacing: DS.Spacing.s) {
            Text("\(number)")
                .font(.subheadline.weight(.bold).monospacedDigit())
                .foregroundStyle(.white)
                .frame(width: 26, height: 26)
                .background(Color.accentColor, in: Circle())
            VStack(alignment: .leading, spacing: DS.Spacing.xxs) {
                Text(step.text)
                if let warning = step.warning, !warning.isEmpty {
                    Label(warning, systemImage: "exclamationmark.triangle.fill")
                        .font(.footnote)
                        .foregroundStyle(.red)
                }
            }
        }
        .padding(.vertical, DS.Spacing.xxs)
        .accessibilityElement(children: .combine)
        .accessibilityLabel("Step \(number). \(step.text)")
    }
}
